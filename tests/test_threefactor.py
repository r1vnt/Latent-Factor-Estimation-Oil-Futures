"""Nesting, identification guards, and the defect the third factor exists to fix.

The last test is the important one: it reproduces the C1-C18 battery's failure
mode on synthetic data with a known two-rate truth, and shows a single kappa
sliding with the maturity window while the two-rate model does not.
"""

from __future__ import annotations

import numpy as np
import pytest

from csr.pricing.threefactor import (A_tau3, ThreeFactorParams, base_system3,
                                     from_two_factor, initial_state3,
                                     scale_variances3)
from csr.pricing.twofactor import A_tau, TwoFactorParams, base_system
from csr.simulate import SS_OIL

DT = 1.0 / 252.0
TAU18 = np.arange(1, 19) / 12.0


def _p3(**kw):
    base = dict(kappa1=4.0, kappa2=0.6, sigma1=0.35, sigma2=0.22,
                sigma_xi=0.18, mu_xi=0.02, mu_xi_star=0.01, lambda1=0.05)
    base.update(kw)
    return ThreeFactorParams(**base)


# ----------------------------------------------------------------- nesting --

def test_sigma2_zero_reproduces_two_factor_A_tau():
    p2 = SS_OIL
    p3 = ThreeFactorParams(
        kappa1=p2.kappa, kappa2=p2.kappa * 0.1,
        sigma1=p2.sigma_chi, sigma2=0.0, sigma_xi=p2.sigma_xi,
        rho1x=p2.rho, mu_xi=p2.mu_xi, mu_xi_star=p2.mu_xi_star,
        lambda1=p2.lambda_chi, lambda2=0.0)
    tau = np.linspace(0.02, 1.5, 60)
    np.testing.assert_allclose(A_tau3(p3, tau), A_tau(p2, tau), atol=1e-12)


def test_sigma2_zero_reproduces_two_factor_system():
    p2 = SS_OIL
    p3 = ThreeFactorParams(
        kappa1=p2.kappa, kappa2=p2.kappa * 0.1,
        sigma1=p2.sigma_chi, sigma2=0.0, sigma_xi=p2.sigma_xi,
        rho1x=p2.rho, mu_xi=p2.mu_xi, mu_xi_star=p2.mu_xi_star,
        lambda1=p2.lambda_chi, lambda2=0.0)
    tau = np.tile(TAU18, (40, 1))
    s2, s3 = base_system(p2, tau, DT), base_system3(p3, tau, DT)

    np.testing.assert_allclose(s3["d"], s2["d"], atol=1e-12)
    np.testing.assert_allclose(s3["Z"][:, :, 0], s2["Z"][:, :, 0], atol=1e-14)
    np.testing.assert_allclose(s3["Z"][:, :, 2], s2["Z"][:, :, 1], atol=1e-14)
    # the dormant factor contributes no process noise in any direction
    np.testing.assert_allclose(s3["Q"][:, 1, :], 0.0, atol=1e-16)
    np.testing.assert_allclose(s3["Q"][:, :, 1], 0.0, atol=1e-16)
    q2 = s2["Q"] if np.asarray(s2["Q"]).ndim == 3 else s2["Q"][None]
    np.testing.assert_allclose(s3["Q"][0, 0, 0], q2[0][0, 0], atol=1e-16)
    np.testing.assert_allclose(s3["Q"][0, 2, 2], q2[0][1, 1], atol=1e-16)
    np.testing.assert_allclose(s3["Q"][0, 0, 2], q2[0][0, 1], atol=1e-16)


def test_A_tau3_is_zero_at_zero_maturity():
    assert A_tau3(_p3(), np.array([0.0])) == pytest.approx(0.0, abs=1e-14)


# ------------------------------------------------------ identification guards --

def test_label_switching_is_blocked():
    """Exchangeable factors must be ordered or multi-start reports false modes."""
    with pytest.raises(ValueError, match="label switching"):
        _p3(kappa1=0.6, kappa2=4.0)
    with pytest.raises(ValueError, match="label switching"):
        _p3(kappa1=2.0, kappa2=2.0)


def test_correlation_matrix_must_be_psd():
    with pytest.raises(ValueError, match="positive semi-definite"):
        _p3(rho12=0.99, rho1x=0.99, rho2x=-0.99)
    _p3(rho12=0.3, rho1x=-0.2, rho2x=0.1)          # valid triple


def test_loadings_separate_front_from_back():
    """The whole point: the two columns must not be near-collinear."""
    Z = base_system3(_p3(), np.tile(TAU18, (5, 1)), DT)["Z"][0]
    ev = np.linalg.eigvalsh(Z.T @ Z)
    assert ev[0] > 1e-3, "three-factor loadings are collinear on this grid"
    assert np.sqrt(ev[-1] / ev[0]) < 40.0


def test_priors_are_stationary_for_both_reverting_factors():
    p = _p3()
    tau = np.tile(TAU18, (3, 1))
    x0, P0 = initial_state3(np.full((3, 18), np.log(70.0)), tau, p)
    assert x0[0] == 0.0 and x0[1] == 0.0
    assert P0[0, 0] == pytest.approx(p.sigma1 ** 2 / (2 * p.kappa1))
    assert P0[1, 1] == pytest.approx(p.sigma2 ** 2 / (2 * p.kappa2))


def test_warm_start_brackets_the_two_factor_kappa():
    p3 = from_two_factor(SS_OIL, kappa_ratio=4.0)
    assert p3.kappa2 < SS_OIL.kappa < p3.kappa1
    assert p3.kappa1 / p3.kappa2 == pytest.approx(4.0)


# ------------------------------------------------------------- the defect ----

def test_single_kappa_slides_with_the_maturity_window():
    """Reproduce the battery's signature on data with a known two-rate truth.

    Fit a single exponential to a curve generated by two, by least squares on
    the loading shape, over three maturity windows. A one-rate model cannot sit
    still; the observed C1-C18 spread of 0.42 across block-outs is this effect.
    """
    p = _p3(kappa1=4.0, kappa2=0.5, sigma1=1.0, sigma2=1.0)
    w1, w2 = 0.5, 0.5

    def best_single_kappa(tau):
        truth = w1 * np.exp(-p.kappa1 * tau) + w2 * np.exp(-p.kappa2 * tau)
        grid = np.linspace(0.05, 8.0, 4000)
        err = [np.sum((np.exp(-k * tau) - truth / (w1 + w2)) ** 2) for k in grid]
        return grid[int(np.argmin(err))]

    front = best_single_kappa(TAU18[:6])     # C1-C6
    full = best_single_kappa(TAU18)          # C1-C18
    back = best_single_kappa(TAU18[6:])      # C7-C18

    assert front > full > back, (front, full, back)
    assert front - back > 0.4, "expected the observed magnitude of sliding"


def test_scale_variances3_gamma_v_zero_is_a_noop():
    p = _p3(gamma_v=0.3)  # nonzero gamma_v, but no rv_lag passed
    sys = base_system3(p, np.tile(TAU18, (5, 1)), DT)
    out = scale_variances3(sys, p, rv_lag=None)
    np.testing.assert_array_equal(out["Q"], sys["Q"])

    p0 = _p3(gamma_v=0.0)
    out0 = scale_variances3(sys, p0, rv_lag=np.ones(5))
    np.testing.assert_array_equal(out0["Q"], sys["Q"])


def test_scale_variances3_scales_chi_block_only():
    p = _p3(gamma_v=0.5, rho1x=0.2, rho2x=-0.1)
    sys = base_system3(p, np.tile(TAU18, (3, 1)), DT)
    rv = np.array([1.0, -1.0, 0.0])
    out = scale_variances3(sys, p, rv_lag=rv)
    s = np.exp(p.gamma_v * rv)

    np.testing.assert_allclose(out["Q"][:, 0, 0], sys["Q"][:, 0, 0] * s)
    np.testing.assert_allclose(out["Q"][:, 1, 1], sys["Q"][:, 1, 1] * s)
    np.testing.assert_allclose(out["Q"][:, 0, 2], sys["Q"][:, 0, 2] * np.sqrt(s))
    np.testing.assert_allclose(out["Q"][:, 1, 2], sys["Q"][:, 1, 2] * np.sqrt(s))
    # xi's own variance is untouched
    np.testing.assert_allclose(out["Q"][:, 2, 2], sys["Q"][:, 2, 2])


def test_two_rate_model_reproduces_its_own_curve_on_every_window():
    """The complement: with both rates free, every window recovers the truth."""
    p = _p3(kappa1=4.0, kappa2=0.5, sigma1=1.0, sigma2=1.0)
    for tau in (TAU18[:6], TAU18, TAU18[6:]):
        got = 0.5 * np.exp(-p.kappa1 * tau) + 0.5 * np.exp(-p.kappa2 * tau)
        want = 0.5 * np.exp(-4.0 * tau) + 0.5 * np.exp(-0.5 * tau)
        np.testing.assert_allclose(got, want, atol=1e-14)
